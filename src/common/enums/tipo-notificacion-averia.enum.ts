/**
 * Tipos de notificación interna (campana).
 * Incluye averías (PBI 2.8) y solicitudes de ausencia RRHH.
 * Distintos de los eventos SMS.
 */
export enum TipoNotificacionAveria {
  AVERIA_REGISTRADA_ADMINISTRADORA = 'AVERIA_REGISTRADA_ADMINISTRADORA',
  AVERIA_ASIGNADA_FONTANERO = 'AVERIA_ASIGNADA_FONTANERO',
  AVERIA_CLASIFICADA_ADMINISTRADORA = 'AVERIA_CLASIFICADA_ADMINISTRADORA',
  SOLICITUD_AUSENCIA_PENDIENTE_ADMINISTRADORA = 'SOLICITUD_AUSENCIA_PENDIENTE_ADMINISTRADORA',
  SOLICITUD_AUSENCIA_APROBADA_FONTANERO = 'SOLICITUD_AUSENCIA_APROBADA_FONTANERO',
  SOLICITUD_AUSENCIA_RECHAZADA_FONTANERO = 'SOLICITUD_AUSENCIA_RECHAZADA_FONTANERO',
  SOLICITUD_MATERIALES_PENDIENTE_ADMINISTRADORA = 'SOLICITUD_MATERIALES_PENDIENTE_ADMINISTRADORA',
  SOLICITUD_MATERIALES_APROBADA_FONTANERO = 'SOLICITUD_MATERIALES_APROBADA_FONTANERO',
  SOLICITUD_MATERIALES_RECHAZADA_FONTANERO = 'SOLICITUD_MATERIALES_RECHAZADA_FONTANERO',
  SALIDA_INVENTARIO_REGISTRADA_ADMINISTRADORA = 'SALIDA_INVENTARIO_REGISTRADA_ADMINISTRADORA',
  ALERTA_REPOSICION_ADMINISTRADORA = 'ALERTA_REPOSICION_ADMINISTRADORA',
  ACTIVIDAD_REQUIERE_CORRECCION_FONTANERO = 'ACTIVIDAD_REQUIERE_CORRECCION_FONTANERO',
}

export function isTipoNotificacionAveriaValido(
  tipo: string,
): tipo is TipoNotificacionAveria {
  return Object.values(TipoNotificacionAveria).includes(
    tipo as TipoNotificacionAveria,
  );
}
